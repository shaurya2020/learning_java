package java;

public class Day_6 {
	public static void main(String[] args) {
	
//		switch expression
		
		int Day = 2;
		
		switch (Day) {
		case 1:
		System.out.println("Monday");
		break;
		case 2:
		System.out.println("Tuesday");
		break;
		case 3:
		System.out.println("Wednesday");
		break;
		default:
		System.out.println("Invalid day");
		}
		
}
}
